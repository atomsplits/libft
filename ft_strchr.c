#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	if (s == NULL)
		return (NULL);
	while (*s)
	{
		if (*s++ == (char)c)
			return ((char *)--s);
	}
	if (*s == (char)c)
		return ((char *)s);
	return (NULL);
}
