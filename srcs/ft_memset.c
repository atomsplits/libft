#include <stdlib.h>

void	*ft_memset(void *s, int c, size_t n)
{
	int		i;
	unsigned char *p = s;
	i = 0;
	while (n > 0)
	{
		*p = c;
		p++;
		n--;
	}
	return (s);
}
