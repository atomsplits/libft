#include <stdlib.h>

size_t	ft_strlcpy(char *dest, const char *src, size_t n)
{
	size_t	i;

	i = 0;
	while (i < n - 1)
	{
		if (*src != '\0')
			*dest++ = *src++;
		i++;
	}
	*dest = '\0';
	return (i);
}
